import { test, expect } from '@playwright/test'
import { API_ORIGIN } from './environment'
const key = { 'X-E2E-Key': 'agentmall-local-e2e' }
test('durable async: queue survives browser closure, real worker completes and HITL remains independent', async ({ page, request, context }) => {
  const control = async (path: string) => {
    const response = await request.post(API_ORIGIN + '/__test/' + path, { headers: key })
    expect(response.ok(), await response.text()).toBeTruthy()
  }
  await control('reset')
  await control('worker-mode')
  const login = async (p: typeof page) => {
    await p.goto('/login')
    await p.getByLabel('账号', { exact: true }).fill('buyer1')
    await p.getByLabel('密码', { exact: true }).fill('AgentMall-demo-2026!')
    await p.getByRole('button', { name: '登录', exact: true }).click()
    await expect(p.getByRole('button', { name: '退出登录' })).toBeVisible()
  }
  await login(page)
  await page.locator('a[href="/agent/workspace"]').first().click()
  await page.getByRole('button', { name: '创建 Thread' }).click()
  await page.getByLabel('Durable Async', { exact: false }).check()
  await page.getByLabel('本次任务').fill('推荐300元以内的静音键盘，不要购买。')
  await page.getByRole('button', { name: '启动新 Run' }).click()
  await expect(page.getByTestId('job-state')).toContainText('QUEUED')
  const restored = page.url()
  await page.close()
  await control('worker-tick')
  const fresh = await context.newPage()
  await fresh.goto(restored)
  await fresh.getByRole('link', { name: '去登录' }).click()
  await fresh.getByLabel('账号', { exact: true }).fill('buyer1')
  await fresh.getByLabel('密码', { exact: true }).fill('AgentMall-demo-2026!')
  await fresh.getByRole('button', { name: '登录', exact: true }).click()
  await expect(fresh.getByTestId('run-status')).toHaveText('COMPLETED')
  await fresh.getByLabel('Durable Async', { exact: false }).check()
  await fresh.getByLabel('本次任务').fill('就买刚才推荐的第二款，一件，送演示宿舍。')
  await fresh.getByRole('button', { name: '启动新 Run' }).click()
  await expect(fresh.getByTestId('job-state')).toContainText('QUEUED')
  await control('worker-tick')
  await expect(fresh.getByTestId('run-status')).toHaveText('WAITING_INPUT')
  const facts = await request.get(API_ORIGIN + '/__test/facts', { headers: key })
  expect((await facts.json()).orders).toBe(0)
  await expect(fresh.getByRole('button', { name: '批准并继续工作流', exact: true })).toBeVisible()
  await fresh.getByRole('button', { name: '批准并继续工作流', exact: true }).click()
  await expect(fresh.getByTestId('job-state')).toContainText('QUEUED')
  await control('worker-tick')
  await expect(fresh.getByTestId('run-status')).toHaveText('COMPLETED')
  await fresh.reload()
  await fresh.getByRole('link', { name: '去登录' }).click()
  await fresh.getByLabel('账号', { exact: true }).fill('buyer1')
  await fresh.getByLabel('密码', { exact: true }).fill('AgentMall-demo-2026!')
  await fresh.getByRole('button', { name: '登录', exact: true }).click()
  await expect(fresh.getByTestId('run-status')).toHaveText('COMPLETED')
  const after = await request.get(API_ORIGIN + '/__test/facts', { headers: key })
  const state = await after.json()
  expect(state.orders).toBe(1)
  expect(state.payment_rows).toHaveLength(0)
  expect(state.provider_http_requests).toBe(0)
  await fresh.screenshot({ path: 'test-results/worker-completed.png', fullPage: true })
})
