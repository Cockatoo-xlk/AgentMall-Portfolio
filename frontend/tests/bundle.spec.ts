import { expect, test } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import path from 'node:path'
import { API_ORIGIN } from './environment'
const key = { 'X-E2E-Key': 'agentmall-local-e2e' }
const root = process.env.AGENTMALL_BUNDLE_EVIDENCE_DIR ?? 'test-results/bundle'
const message = '预算5000元，帮我搭配一套居家办公设备，包括27英寸显示器、无线键盘、鼠标和耳机。先推荐，不要购买。'
test.beforeEach(async ({ request, page }) => {
  expect((await request.post(API_ORIGIN + '/__test/reset', { headers: key, data: {} })).ok()).toBeTruthy()
  expect((await request.post(API_ORIGIN + '/__test/sdk-mode', { headers: key, data: { program: 'bundle' } })).ok()).toBeTruthy()
  await page.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
  await page.goto('/login')
  await page.getByLabel('账号', { exact: true }).fill('buyer1')
  await page.getByLabel('密码', { exact: true }).fill('AgentMall-demo-2026!')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.locator('a[href="/agent/workspace"]').first().click()
  await page.getByLabel('运行模式').selectOption('multi')
  await page.getByRole('button', { name: '创建 Thread' }).click()
})
test('bundle: independent four-category recommendation, refresh, one confirmed multi-SKU order', async ({ page, request }) => {
  await page.getByLabel('本次任务').fill(message)
  await page.getByRole('button', { name: '启动新 Run' }).click()
  await expect(page.getByTestId('run-status')).toHaveText('COMPLETED')
  await expect(page.getByTestId('bundle-item')).toHaveCount(4)
  await expect(page.getByTestId('bundle-offer')).toContainText('5,000.00')
  await expect(page.getByTestId('bundle-offer')).toContainText('不是购买授权')
  const f = await (await request.get(API_ORIGIN + '/__test/facts', { headers: key })).json()
  expect(f.orders).toBe(0)
  expect(f.proposals).toBe(0)
  expect(f.sdk.tools).toContain('retrieve_bundle_candidates')
  await mkdir(root, { recursive: true })
  await page.screenshot({ path: path.join(root, '01-bundle-recommendation.png'), fullPage: true })
  await page.getByRole('region', { name: '组合购物方案', exact: true }).screenshot({ path: path.join(root, '01-bundle-panel.png') })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByTestId('bundle-item')).toHaveCount(4)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('region', { name: '组合购物方案', exact: true }).screenshot({ path: path.join(root, '03-mobile-bundle.png') })
  await page.setViewportSize({ width: 1280, height: 720 })
  await page.reload()
  await page.getByRole('link', { name: '去登录' }).click()
  await page.getByLabel('账号', { exact: true }).fill('buyer1')
  await page.getByLabel('密码', { exact: true }).fill('AgentMall-demo-2026!')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByTestId('bundle-item')).toHaveCount(4)
  await page.getByLabel('选择此整套方案').check()
  await page.getByLabel('本次任务').fill('就买这套，每样一件，送演示宿舍。')
  await page.getByRole('button', { name: '启动新 Run' }).click()
  await expect(page.getByTestId('run-status')).toHaveText('WAITING_INPUT')
  const waiting = await (await request.get(API_ORIGIN + '/__test/facts', { headers: key })).json()
  expect(waiting.orders).toBe(0)
  expect(waiting.proposal_rows[0].canonical_payload.items).toHaveLength(4)
  await page.screenshot({ path: path.join(root, '02-bundle-confirmation.png'), fullPage: true })
  await page.getByRole('heading', { name: '确认购买快照' }).locator('..').screenshot({ path: path.join(root, '02-checkout-panel.png') })
  // Explicit TEST_OPERATOR decision in a synthetic MockTransport environment.
  await page.getByRole('button', { name: '批准并继续工作流' }).click()
  await expect(page.getByTestId('run-status')).toHaveText('COMPLETED')
  await page.reload()
  const done = await (await request.get(API_ORIGIN + '/__test/facts', { headers: key })).json()
  expect(done.order_rows).toHaveLength(1)
  expect(done.order_rows[0].status).toBe('PENDING_PAYMENT')
  expect(done.payment_rows).toHaveLength(0)
  expect(done.confirmation_rows).toHaveLength(1)
  expect(done.confirmation_rows[0].consumed_at).not.toBeNull()
  expect(done.real_model_calls).toBe(0)
  expect(done.provider_http_requests).toBe(0)
  expect(done.blocked_external_attempts).toBe(0)
})
test('bundle: insufficient budget keeps required categories with zero proposals', async ({ page, request }) => {
  await page.getByLabel('本次任务').fill(message.replace('5000元', '1元'))
  await page.getByRole('button', { name: '启动新 Run' }).click()
  await expect(page.getByTestId('run-status')).toHaveText('COMPLETED')
  await expect(page.getByRole('status').filter({ hasText: '没有完整可行方案' })).toBeVisible()
  await expect(page.getByTestId('bundle-offer')).toHaveCount(0)
  const f = await (await request.get(API_ORIGIN + '/__test/facts', { headers: key })).json()
  expect(f.orders).toBe(0)
  expect(f.proposals).toBe(0)
})
