test('V216 C: two independent HITL approvals create one case and one replacement order', async ({ page, request }) => {
  const id = await delivered(request)
  const baseline = await facts(request)
  await control(request, '/sdk-mode', { program: 'return_replace', order_id: id })
  await start(page, replace(id))
  await expect(page.getByRole('heading', { name: '确认退货申请' })).toBeVisible()
  expect((await facts(request)).case_rows).toHaveLength(0)
  await page.getByRole('button', { name: '批准并继续工作流' }).click()
  await expect(page.getByRole('heading', { name: '确认购买快照' })).toBeVisible()
  const middle = await facts(request)
  expect(middle.case_rows).toHaveLength(1)
  expect(middle.orders).toBe(baseline.orders)
  const first = middle.confirmation_rows.find((c: { proposal_id: string }) => c.proposal_id === middle.case_rows[0].proposal_id)
  const buyer = await auth(request)
  const pending = middle.run_rows[0].pending_confirmation
  const wrong = await request.post(API + `/agent/threads/${middle.run_rows[0].thread_id}/resume`, { headers: buyer, data: { run_id: middle.run_rows[0].id, interrupt_id: pending.interrupt_id, proposal_id: pending.proposal_id, confirmation_id: first.id, request_id: crypto.randomUUID() } })
  expect(wrong.status()).toBe(409)
  await page.getByRole('button', { name: '批准并继续工作流' }).click()
  await expect(page.getByTestId('run-status')).toHaveText('COMPLETED')
  const f = await facts(request)
  expect(f.orders).toBe(baseline.orders + 1)
  expect(f.case_rows).toHaveLength(1)
  expect(f.confirmations).toBe(baseline.confirmations + 2)
  const approvals = f.confirmation_rows.slice(baseline.confirmations)
  expect(new Set(approvals.map((c: { id: string }) => c.id)).size).toBe(2)
  expect(approvals.every((c: { consumed_at: string | null }) => c.consumed_at !== null)).toBe(true)
  expect(f.order_rows.filter((o: { status: string }) => o.status === 'PENDING_PAYMENT')).toHaveLength(1)
  expect(f.payment_rows).toHaveLength(baseline.payment_rows.length)
  expect(f.refund_rows).toHaveLength(0)
  await expect(page.getByTestId('resource-case')).toContainText('REQUESTED')
  await expect(page.getByTestId('resource-order').filter({ hasText: 'PENDING_PAYMENT' })).toHaveCount(1)
})
test('V216 C: rejecting return cannot authorize replacement checkout', async ({ page, request }) => {
  const id = await delivered(request)
  const baseline = await facts(request)
  await control(request, '/sdk-mode', { program: 'return_replace', order_id: id })
  await start(page, replace(id))
  await expect(page.getByRole('heading', { name: '确认退货申请' })).toBeVisible()
  await decide(page, 'reject')
  // The separate purchase intent may still prepare a proposal. It is not authorized
  // by the return decision: wait for that actual persisted interrupt, then reject it.
  await expect(page.getByRole('heading', { name: '确认购买快照' })).toBeVisible()
  const middle = await facts(request)
  expect(middle.case_rows).toHaveLength(0)
  expect(middle.orders).toBe(baseline.orders)
  expect(middle.confirmations).toBe(baseline.confirmations + 1)
  expect(middle.confirmation_rows.at(-1).decision).toBe('reject')
  expect(middle.proposal_rows.at(-1).action_type).toBe('CHECKOUT')
  expect(middle.proposal_rows.at(-1).status).toBe('PENDING')
  await decide(page, 'reject')
  await expect(page.getByTestId('run-status')).toHaveText('COMPLETED')
  const f = await facts(request)
  expect(f.case_rows).toHaveLength(0)
  expect(f.orders).toBe(baseline.orders)
  expect(f.confirmations).toBe(baseline.confirmations + 2)
  expect(f.confirmation_rows.slice(baseline.confirmations).every((c: { decision: string; consumed_at: string | null }) => c.decision === 'reject' && c.consumed_at === null)).toBe(true)
})
